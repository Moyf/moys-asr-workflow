// Repository-only documentation assets. Never crawl docs or user-selected files.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {dirname, resolve, relative, sep} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {runInNewContext} from 'node:vm';
import {createHash} from 'node:crypto';

export const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const extraDocuments = Object.freeze(['README.md', 'TOOL_PAGE_GUIDE.md', 'AGENTS.md', 'shared/README.md']);
export const vendors = Object.freeze([
  {name:'marked', version:'18.1.3', files:[
    ['lib/marked.umd.js', 'marked.umd.js', 'c34a221dc89e91833a88822e7717b8a0cf27118f8c9a8779dffb48a6be31f97a'],
    ['LICENSE', 'LICENSE', '8e3a3f82f59a60958f56ca08f445647c32a4733dc7ca6c2c46f6eb898471ab9c'],
  ]},
  {name:'dompurify', version:'3.4.17', files:[
    ['dist/purify.min.js', 'purify.min.js', 'cd37898f9782adf54820c413191b5691803f0f137c799d6edcfd38523b4c2c31'],
    ['LICENSE', 'LICENSE', 'cfc7749b96f63bd31c3c42b5c471bf756814053e847c10f3eb003417bc523d30'],
    ['LICENSE-MPL', 'LICENSE-MPL', 'fab3dd6bdab226f1c08630b1dd917e11fcb4ec5e1e020e2c16f83a0a13863e85'],
  ]},
]);

export async function collectDocuments(root = projectRoot) {
  const window = {};
  runInNewContext(await readFile(resolve(root, 'tools/catalog.js'), 'utf8'), {window},
    {timeout:1000, codeGeneration:{strings:false, wasm:false}});
  if (!Array.isArray(window.MAWToolCatalog)) throw new Error('Missing tool catalog');
  const paths = new Set([...extraDocuments, ...window.MAWToolCatalog.map(tool => tool.docs)]);
  const documents = {};
  const toolsRoot = resolve(root, 'tools');
  for (const path of [...paths].sort()) {
    if (typeof path !== 'string' || !/^(?:[a-zA-Z0-9_-]+\/)*[a-zA-Z0-9_.-]+$/.test(path)
      || !(path.endsWith('.md') || path === 'merge-flow.mjs')) throw new Error(`Unsupported catalog document: ${path}`);
    const absolute = resolve(toolsRoot, path);
    if (relative(toolsRoot, absolute).startsWith('..' + sep)) throw new Error('Document outside tools');
    documents[path] = {format:path.endsWith('.md') ? 'markdown' : 'source', text:await readFile(absolute, 'utf8')};
  }
  return documents;
}

export async function documentationAsset(root = projectRoot) {
  const documents = await collectDocuments(root);
  const json = JSON.stringify({version:1, documents}, null, 2)
    .replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
  return '/* Generated by scripts/build-tool-docs.mjs --write; edit the source documents. */\n'
    + '(function () {\n  "use strict";\n  const data = ' + json + ';\n'
    + '  Object.values(data.documents).forEach(Object.freeze);\n'
    + '  Object.freeze(data.documents);\n  window.MAWToolDocs = Object.freeze(data);\n})();\n';
}

export async function buildToolDocs({root = projectRoot, write = false} = {}) {
  const outputs = [{path:resolve(root, 'tools/tool-docs-data.js'), bytes:Buffer.from(await documentationAsset(root))}];
  for (const vendor of vendors) {
    const packageRoot = resolve(root, 'node_modules', vendor.name);
    // --check needs only tracked files and standard Node, not pnpm/node_modules.
    const metadataText = write ? await readFile(resolve(packageRoot, 'package.json'), 'utf8')
      .catch(error => {if (error.code === 'ENOENT') return null; throw error;}) : null;
    if (metadataText && JSON.parse(metadataText).version !== vendor.version) throw new Error(`${vendor.name}: expected ${vendor.version}`);
    for (const [source, name, hash] of vendor.files) {
      const path = resolve(root, 'tools/shared/vendor', `${vendor.name}-${vendor.version}`, name);
      const bytes = await readFile(metadataText ? resolve(packageRoot, source) : path);
      if (createHash('sha256').update(bytes).digest('hex') !== hash) throw new Error(`Unexpected official vendor bytes: ${vendor.name}/${name}. Reinstall pinned packages and run --write`);
      outputs.push({path, bytes});
    }
  }
  const stale = [];
  for (const output of outputs) {
    if (write) {
      await mkdir(dirname(output.path), {recursive:true});
      await writeFile(output.path, output.bytes); // Unmodified official distribution and full license bytes.
    } else {
      const current = await readFile(output.path).catch(error => {if (error.code === 'ENOENT') return null; throw error;});
      if (!current?.equals(output.bytes)) stale.push(relative(root, output.path).split(sep).join('/'));
    }
  }
  if (stale.length) throw new Error(`Stale tool documentation assets: ${stale.join(', ')}. Run node scripts/build-tool-docs.mjs --write`);
  return outputs.length;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  if (args.length !== 1 || !['--write', '--check'].includes(args[0])) {
    console.error('Usage: node scripts/build-tool-docs.mjs --write|--check');
    process.exitCode = 2;
  } else {
    try {
      const count = await buildToolDocs({write:args[0] === '--write'});
      console.log(`Tool documentation assets ${args[0] === '--write' ? 'written' : 'fresh'} (${count} files).`);
    } catch (error) {console.error(error.message); process.exitCode = 1;}
  }
}
