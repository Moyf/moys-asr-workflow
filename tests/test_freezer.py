class StripGpuPinsTests(unittest.TestCase):
    def test_strips_local_version_suffix(self) -> None:
        self.assertEqual(
            freezer_mod.strip_gpu_pins("torch==2.13.0+cu130"),
            "torch==2.13.0",
        )

    def test_no_cu_pin_is_identity(self) -> None:
        line = "numba>=0.61.0"
        self.assertEqual(freezer_mod.strip_gpu_pins(line), line)


class CpuRequirementsLinesTests(unittest.TestCase):
    def test_moss_input_drops_darwin_branch_and_strips_marker_and_cu(self) -> None:
        lines = freezer_mod.cpu_requirements_lines(MOSS_IN)
        # 源注释不带入（头部注释由 cpu_input_text 负责），darwin 分支丢弃，
        # 剩余依赖行无 marker / 无 +cu
        self.assertNotIn("# MOSS 依赖声明（GPU 分支 pin cu130 本地版本）。", lines)
        self.assertEqual(lines, ["av>=14.0", "torch==2.13.0", "torchaudio==2.11.0", "safetensors>=0.6.2"])
        self.assertNotIn("sys_platform", "".join(lines))
        self.assertNotIn("+cu130", "".join(lines))
        self.assertNotIn("darwin", "".join(lines))

    def test_export_pin_lines_also_cpu_normalized(self) -> None:
        lines = freezer_mod.cpu_requirements_lines(
            "torch==2.13.0+cu130 ; sys_platform != 'darwin'\n"
            "torch==2.13.0 ; sys_platform == 'darwin'\n"
            "audioop-lts==0.2.2 ; python_full_version >= '3.13'\n"
        )
        # darwin 分支丢弃；!= darwin 条件剥离；无关 marker 保留
        self.assertEqual(lines, ["torch==2.13.0", "audioop-lts==0.2.2 ; python_full_version >= '3.13'"])

    def test_cpu_input_text_ends_with_lf_and_accepts_header(self) -> None:
        text = freezer_mod.cpu_input_text(MOSS_IN, header="# CPU 变体\n")
        self.assertTrue(text.endswith("\n"))
        self.assertTrue(text.startswith("# CPU 变体\n"))
        self.assertIn("torch==2.13.0\n", text)


