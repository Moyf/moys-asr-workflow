class FreezeCommandTests(unittest.TestCase):
    def test_local_main_uses_uv_export(self) -> None:
        self.assertEqual(
            freezer_mod.main_freeze_command(UV, LOCAL_SPEC, BUILD),
            [str(UV), "export", "--frozen", "--extra", "local", "--no-dev",
             "--format", "requirements-txt", "-o", str(BUILD / "requirements-local.txt")],
        )

    def test_ocr_main_uses_uv_export(self) -> None:
        self.assertEqual(
            freezer_mod.main_freeze_command(UV, OCR_SPEC, BUILD),
            [str(UV), "export", "--frozen", "--extra", "ocr", "--no-dev",
             "--format", "requirements-txt", "-o", str(BUILD / "requirements-ocr.txt")],
        )

    def test_moss_main_compiles_in_file_with_cu130_index(self) -> None:
        self.assertEqual(
            freezer_mod.main_freeze_command(UV, MOSS_SPEC, BUILD),
            [str(UV), "pip", "compile", "moss-requirements.in", "-p", "3.11",
             "--extra-index-url", "https://download.pytorch.org/whl/cu130",
             "--index-strategy", "unsafe-best-match",
             "-o", str(BUILD / "requirements-moss.txt")],
        )

    def test_cpu_variants_compile_generated_input_in_build_dir(self) -> None:
        for spec, name in ((LOCAL_SPEC, "local"), (MOSS_SPEC, "moss")):
            with self.subTest(spec=spec.key):
                self.assertEqual(
                    freezer_mod.cpu_freeze_command(UV, spec, BUILD),
                    [str(UV), "pip", "compile", str(BUILD / f"{name}-cpu-requirements.in"),
                     "-p", "3.11", "--generate-hashes",
                     "--index-strategy", "unsafe-best-match",
                     "-o", str(BUILD / f"requirements-{name}-cpu.txt")],
                )

    def test_ocr_has_no_cpu_variant(self) -> None:
        self.assertIsNone(freezer_mod.cpu_freeze_command(UV, OCR_SPEC, BUILD))


class EnsureFrozenTests(unittest.TestCase):
    def _temp_build_dir(self) -> Path:
        build = Path(tempfile.mkdtemp()) / "build"
        build.mkdir(parents=True)
        self.addCleanup(lambda: __import__("shutil").rmtree(build.parent, ignore_errors=True))
        return build

    def _fake_run(self, calls: list[list[str]]) -> object:
        def run(command: list[str]) -> object:
            calls.append(command)
            index = command.index("-o")
            Path(command[index + 1]).write_text(EXPORT_SAMPLE, encoding="utf-8")
            return 0

        return run

    def test_main_generated_when_missing_and_skipped_when_present(self) -> None:
        build = self._temp_build_dir()
        calls: list[list[str]] = []
        freezer_mod.ensure_frozen(UV, LOCAL_SPEC, cpu=False, build_dir=build, run=self._fake_run(calls))
        self.assertEqual(calls[0][1:3], ["export", "--frozen"])
        # 已存在则不再触发
        before = len(calls)
        freezer_mod.ensure_frozen(UV, LOCAL_SPEC, cpu=False, build_dir=build, run=self._fake_run(calls))
        self.assertEqual(len(calls), before)

    def test_local_cpu_exports_main_first_then_compiles(self) -> None:
        build = self._temp_build_dir()
        calls: list[list[str]] = []
        emitted: list[str] = []
        freezer_mod.ensure_frozen(
            UV, LOCAL_SPEC, cpu=True, build_dir=build,
            run=self._fake_run(calls),
            emit=emitted.append,
        )
        # 先 export 主清单（提取直接依赖的源），再 compile CPU 变体
        self.assertEqual(calls[0][1:3], ["export", "--frozen"])
        self.assertEqual(calls[1][1:3], ["pip", "compile"])
        self.assertIn("--generate-hashes", calls[1])
        # 生成式 in 文件已落盘，且内容被 CPU 归一化（无 +cu130）
        cpu_in = build / "local-cpu-requirements.in"
        self.assertTrue(cpu_in.is_file())
        content = cpu_in.read_text(encoding="utf-8")
        self.assertIn("funasr==1.4.2", content)
        self.assertIn("torch==2.13.0", content)
        self.assertNotIn("+cu130", content)
        self.assertIn("正在生成", "".join(emitted))

    def test_local_cpu_reuses_existing_main_export(self) -> None:
        build = self._temp_build_dir()
        (build / "requirements-local.txt").write_text(EXPORT_SAMPLE, encoding="utf-8")
        calls: list[list[str]] = []
        freezer_mod.ensure_frozen(UV, LOCAL_SPEC, cpu=True, build_dir=build, run=self._fake_run(calls))
        # 主清单已存在，只执行 compile
        self.assertEqual(len(calls), 1)
        self.assertEqual(calls[0][1:3], ["pip", "compile"])

    def test_moss_cpu_derives_input_from_in_file(self) -> None:
        build = self._temp_build_dir()
        in_path = build.parent / "moss-requirements.in"
        in_path.write_text(MOSS_IN, encoding="utf-8")
        calls: list[list[str]] = []

        with unittest.mock.patch.object(
            freezer_mod.Path, "read_text", autospec=True
        ) as read_text:
            read_text.side_effect = lambda self, **kw: (
                MOSS_IN if Path(self).name == "moss-requirements.in" else "unexpected"
            )
            freezer_mod.ensure_frozen(UV, MOSS_SPEC, cpu=True, build_dir=build, run=self._fake_run(calls))

        self.assertEqual(len(calls), 1)
        self.assertEqual(calls[0][1:3], ["pip", "compile"])
        self.assertNotIn("extra-index-url", calls[0])
        cpu_in = build / "moss-cpu-requirements.in"
        self.assertTrue(cpu_in.is_file())
        content = cpu_in.read_text(encoding="utf-8")
        self.assertIn("torch==2.13.0\n", content)
        self.assertNotIn("; sys_platform", content)

    def test_ocr_cpu_variant_never_runs(self) -> None:
        build = self._temp_build_dir()
        calls: list[list[str]] = []
        freezer_mod.ensure_frozen(UV, OCR_SPEC, cpu=True, build_dir=build, run=self._fake_run(calls))
        self.assertEqual(calls, [])

    def test_existing_cpu_txt_skips_generation(self) -> None:
        build = self._temp_build_dir()
        (build / "requirements-moss-cpu.txt").write_text("torch==2.13.0\n", encoding="utf-8")
        calls: list[list[str]] = []
        freezer_mod.ensure_frozen(UV, MOSS_SPEC, cpu=True, build_dir=build, run=self._fake_run(calls))
        self.assertEqual(calls, [])


